// Regenerates src/lib/echo/demo-scores.ts: each demo slot's score against its labels, shown in the app's
// accuracy card. Local only, no provider calls. `npm run preflight` fails if this file is stale.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import ts from "typescript";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const load = createRequire(import.meta.url);
load.extensions[".ts"] = (module, filename) => {
  const code = ts.transpileModule(fs.readFileSync(filename, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true },
  }).outputText;
  module._compile(code, filename);
};
const { parsePortableTrace } = load("../src/lib/echo/portable.ts");
const { parseLabelSheet, scoreTrace } = load("../src/lib/echo/evaluation.ts");

const domainOf = (value) => value.replace(/(https?:\/\/[^\s/]+)\S*/g, (_, origin) => origin.replace(/^https?:\/\/(www\.)?/, ""));

// Runs made before the 2026-11-12 afternoon changes (retelling check, page HTML source links, publisher-date reader)
// used an earlier Echo; when a claim also has a newer run, the card marks the older ones so a judge does not read
// their errors as today's behavior.
const SOURCE_LINK_FIXES_AT = "2026-11-13T00:30:00.000Z"; // 4:30pm PT, after the HTML-link commits (961aaaf, 976a271)

// Every scored live run of the same claim (the bundled one plus evaluation/runs/<name>.*.echo.json), oldest first,
// so the card shows whether the bundled run was a lucky pick.
function allRuns(name, bundled, sheet) {
  const dir = path.join(root, "evaluation", "runs");
  const others = fs.existsSync(dir)
    ? fs.readdirSync(dir).filter((file) => file.startsWith(`${name}.`) && file.endsWith(".echo.json")).sort()
      .map((file) => {
        const analysis = parsePortableTrace(JSON.parse(fs.readFileSync(path.join(dir, file), "utf8")));
        if (!analysis) throw new Error(`evaluation/runs/${file}: trace invalid`);
        return analysis;
      })
    : [];
  return [bundled, ...others]
    .map((analysis) => {
      const score = scoreTrace(analysis, sheet);
      return { createdAt: analysis.createdAt, bundled: analysis === bundled, earlierEcho: analysis.createdAt < SOURCE_LINK_FIXES_AT, matched: score.matched, exactKinds: score.exactKinds, settledMistakes: score.settledMistakes, abstentions: score.abstentions };
    })
    .sort((left, right) => left.createdAt.localeCompare(right.createdAt))
    // The mark only means something next to a run made with the fixed Echo; when every run predates the fixes
    // (brain, phones, goldfish as of 11/12) the card compares like with like and shows no marks.
    .map((run, _, runs) => ({ ...run, earlierEcho: run.earlierEcho && runs.some((other) => !other.earlierEcho) }));
}

export function computeDemoScores() {
  const workbench = fs.readFileSync(path.join(root, "src/app/demo-slots.ts"), "utf8");
  const scores = {};
  for (const [, tracePath] of workbench.matchAll(/capturedTrace:\s*"([^"]+)"/g)) {
    const name = path.basename(tracePath, ".echo.json");
    const labelsFile = path.join(root, "evaluation", `${name}.labels.json`);
    if (!fs.existsSync(labelsFile)) continue;
    const analysis = parsePortableTrace(JSON.parse(fs.readFileSync(path.join(root, "public", tracePath), "utf8")));
    const sheet = parseLabelSheet(JSON.parse(fs.readFileSync(labelsFile, "utf8")));
    if (!analysis || !sheet) throw new Error(`${name}: trace or labels invalid`);
    const score = scoreTrace(analysis, sheet);
    if (!score.reviewed) continue;
    scores[tracePath] = {
      traceCreatedAt: analysis.createdAt,
      matched: score.matched,
      exactKinds: score.exactKinds,
      settledMistakes: score.settledMistakes,
      abstentions: score.abstentions,
      derivedGold: score.derivedGold,
      derivedCorrect: score.derivedCorrect,
      exactEdges: score.exactEdges,
      missingLabeled: score.missingReviewed.length,
      disagreements: score.disagreements.map((entry) => ({ title: entry.title.slice(0, 120), expected: domainOf(entry.expected), observed: domainOf(entry.observed) })),
      runs: allRuns(name, analysis, sheet),
    };
  }
  return scores;
}

export function renderDemoScores(scores) {
  return `// Generated by \`npm run eval:demo-scores\` from evaluation/*.labels.json. Do not edit by hand.\n`
    + `// Labels were made by Claude (AI) from full pages, not by a human; the card in the app says so.\n`
    + `export type DemoScore = { traceCreatedAt: string; matched: number; exactKinds: number; settledMistakes: number; abstentions: number; derivedGold: number; derivedCorrect: number; exactEdges: number; missingLabeled: number; disagreements: Array<{ title: string; expected: string; observed: string }>; runs: DemoRun[] };\n`
    + `export type DemoRun = { createdAt: string; bundled: boolean; earlierEcho: boolean; matched: number; exactKinds: number; settledMistakes: number; abstentions: number };\n\n`
    + `export const DEMO_SCORES: Record<string, DemoScore> = ${JSON.stringify(scores, null, 2)};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const out = path.join(root, "src/lib/echo/demo-scores.ts");
  fs.writeFileSync(out, renderDemoScores(computeDemoScores()));
  process.stdout.write(`Wrote ${path.relative(root, out)}\n`);
}
